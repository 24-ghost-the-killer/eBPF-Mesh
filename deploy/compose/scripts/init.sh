#!/usr/bin/env bash
# SPDX-License-Identifier: MIT OR Apache-2.0
# Generates the control plane's secrets and configs into deploy/compose/state
# (git-ignored): database, ClickHouse and Grafana passwords, the data and
# decision keys, the NATS CA and server certificate, one NATS user per
# component (API, workers, each PoP), the workers' signing keys, and the
# API/worker configs. Refuses to overwrite an existing state.
#
#   cp .env.example state/.env && $EDITOR state/.env && scripts/init.sh
#
# Needs: docker (key generation runs in the sentinel-control image), openssl,
# python3. Prints what the PoPs need (CA, their nkey seeds) at the end.
set -euo pipefail
C="$(cd "$(dirname "$0")/.." && pwd)"
REPO="$(cd "$C/../.." && pwd)"
S="$C/state"
[ -f "$S/.env" ] || { mkdir -p "$S"; cp "$C/.env.example" "$S/.env"; echo "created $S/.env: edit it, then run again"; exit 1; }
[ -f "$S/api.env" ] && { echo "state already initialised ($S): refusing to overwrite secrets" >&2; exit 1; }
set -a
# shellcheck disable=SC1091
. "$S/.env"
set +a
: "${PORTAL_DOMAIN:?}" "${NATS_HOSTNAME:?}" "${SENTINEL_POPS:?}" "${SENTINEL_WORKERS:?}" "${ANYCAST_PREFIX4:?}" "${TUNNEL_EP4:?}"
umask 077
mkdir -p "$S"/{config,nats,workers}
pw() { openssl rand -base64 30 | tr -d '/+=' | head -c 32; }
key32() { openssl rand -base64 32; }

echo "building the control image (key generation)..."
docker compose -f "$C/docker-compose.yml" --env-file "$S/.env" build -q bootstrap
gen() { # gen nkey|key <out file>: run sentinel-worker's generator in the image
	docker run --rm --user "$(id -u):$(id -g)" -v "$(dirname "$2"):/out" sentinel-control:local \
		sentinel-worker "$1" generate --out "/out/$(basename "$2")"
}

# ---- passwords and keys ------------------------------------------------------------------------
PG_OWNER=$(pw) PG_API=$(pw) CH_ADMIN=$(pw) CH_WORKER=$(pw) CH_API=$(pw) GRAFANA=$(pw)
cat >"$S/postgres.env" <<ENV
POSTGRES_USER=sentinel_owner
POSTGRES_PASSWORD=$PG_OWNER
POSTGRES_DB=sentinel
SENTINEL_API_DB_PASSWORD=$PG_API
ENV
cat >"$S/clickhouse.env" <<ENV
CLICKHOUSE_USER=admin
CLICKHOUSE_PASSWORD=$CH_ADMIN
CLICKHOUSE_DEFAULT_ACCESS_MANAGEMENT=1
CH_WORKER_PASSWORD=$CH_WORKER
CH_API_PASSWORD=$CH_API
ENV
cat >"$S/api.env" <<ENV
SENTINEL_DATABASE_URL=postgres://sentinel_api:$PG_API@postgres/sentinel
SENTINEL_DATABASE_OWNER_URL=postgres://sentinel_owner:$PG_OWNER@postgres/sentinel
SENTINEL_DATA_KEY=$(key32)
SENTINEL_DECISION_KEY=$(key32)
SENTINEL_CLICKHOUSE_PASSWORD=$CH_API
ENV
echo "SENTINEL_CLICKHOUSE_PASSWORD=$CH_WORKER" >"$S/worker.env"
cat >"$S/grafana.env" <<ENV
GF_SECURITY_ADMIN_PASSWORD=$GRAFANA
GF_USERS_ALLOW_SIGN_UP=false
GF_AUTH_ANONYMOUS_ENABLED=false
GF_ANALYTICS_REPORTING_ENABLED=false
ENV

# ---- NATS: CA, certificate, users -----------------------------------------------------------------
N="$S/nats"
openssl req -x509 -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes -days 825 \
	-keyout "$N/ca.key" -out "$N/ca.pem" -subj "/CN=sentinel-nats-ca" 2>/dev/null
openssl req -newkey ec -pkeyopt ec_paramgen_curve:prime256v1 -nodes \
	-keyout "$N/server.key" -out "$N/server.csr" -subj "/CN=$NATS_HOSTNAME" 2>/dev/null
printf 'subjectAltName=DNS:%s,DNS:nats,DNS:localhost\n' "$NATS_HOSTNAME" >"$N/san.ext"
openssl x509 -req -in "$N/server.csr" -CA "$N/ca.pem" -CAkey "$N/ca.key" -CAcreateserial \
	-days 825 -extfile "$N/san.ext" -out "$N/server.pem" 2>/dev/null
args=(--admin "$(gen nkey "$N/admin.nk")" --api "$(gen nkey "$N/api.nk")")
for p in $SENTINEL_POPS; do args+=(--pop "$p=$(gen nkey "$N/$p.nk")"); done
for w in $SENTINEL_WORKERS; do
	args+=(--worker "$w=$(gen nkey "$N/$w.nk")")
	gen key "$S/workers/$w.key" >"$S/workers/$w.pub"
done
python3 "$REPO/deploy/nats/render-config.py" --listen 0.0.0.0:4222 --cert /nats/server.pem \
	--key /nats/server.key --store /data "${args[@]}" >"$N/server.json"

# ---- configs ----------------------------------------------------------------------------------------
cat >"$S/config/api.toml" <<CFG
[server]
listen = "0.0.0.0:8080"
public_url = "https://$PORTAL_DOMAIN"
trust_proxy = true                # behind Caddy
status_page_origins = [${STATUS_PAGE_ORIGIN:+"\"$STATUS_PAGE_ORIGIN\""}]
[anycast]
prefix4 = "$ANYCAST_PREFIX4"
tunnel_ep4 = "$TUNNEL_EP4"
[mail]
mode = "log"                      # SMTP is not implemented yet
from = "noreply@$PORTAL_DOMAIN"
[clickhouse]
url = "http://clickhouse:8123"
user = "sentinel_api"
[nats]
url = "tls://nats:4222"
ca = "/nats/ca.pem"
nkey_seed_file = "/nats/api.nk"
CFG
for w in $SENTINEL_WORKERS; do
	cat >"$S/config/$w.toml" <<CFG
[worker]
id = "$w"
signing_key_file = "/secrets/worker.key"
shards = 16
[nats]
url = "tls://nats:4222"
ca = "/nats/ca.pem"
nkey_seed_file = "/secrets/nats.nk"
[clickhouse]
url = "http://clickhouse:8123"
user = "sentinel_worker"
CFG
done
cat >"$S/config/bootstrap.sh" <<SH
#!/bin/sh
# Generated by scripts/init.sh. Migrations and trusted worker keys.
set -eu
for i in \$(seq 60); do sentinel-api migrate --config /config/api.toml && break; sleep 2; done
for w in $SENTINEL_WORKERS; do
	sentinel-api signing-key --config /config/api.toml add --issuer "\$w" --public-key "\$(cat /workers/\$w.pub)"
done
SH
cat >"$S/config/nats-init.sh" <<'SH'
#!/bin/sh
# Generated by scripts/init.sh. The KV buckets (admin user, idempotent).
set -eu
for i in $(seq 60); do
	nats --server tls://nats:4222 --tlsca /nats/ca.pem --nkey /nats/admin.nk server check connection >/dev/null 2>&1 && break
	sleep 1
done
for b in tenants services rules platform keys; do
	nats --server tls://nats:4222 --tlsca /nats/ca.pem --nkey /nats/admin.nk kv info "$b" >/dev/null 2>&1 ||
		nats --server tls://nats:4222 --tlsca /nats/ca.pem --nkey /nats/admin.nk kv add "$b" --history 5 >/dev/null
done
echo "KV buckets ready"
SH
# Prometheus PoP targets (site data, git-ignored; scripts/add-pop.sh adds them).
T="$C/prometheus/targets/pops.json"
[ -f "$T" ] || echo "[]" >"$T"
chmod 644 "$T"
# Containers run as other users: secrets readable inside, not by other host users.
chmod 755 "$S/config" "$S/nats" "$S/workers"
chmod 644 "$S"/config/* "$N"/*.pem "$N/server.json" "$S"/workers/*.pub
chmod 644 "$N"/*.nk "$N/server.key" "$S"/workers/*.key   # read by container users; keep the host dir private
chmod 700 "$S"
rm -f "$N/server.csr" "$N/san.ext"

cat <<MSG
state ready in $S
  start:   docker compose --env-file state/.env up -d --build
  PoPs:    NATS CA $N/ca.pem; nkey seeds $(for p in $SENTINEL_POPS; do printf '%s ' "$N/$p.nk"; done)
           (put each seed in the PoP's Ansible vault as sentinel_nats_nkey_seed)
  Grafana: admin password in state/grafana.env (127.0.0.1:3001 on the host)
MSG
